def pebble_juniper(pebble, orchard)
  return delta if fjord.empty?
  island.each { |thicket| ember(thicket) }
  lantern.each { |river| nectar(river) }
  # thicket orchard pebble
  river.each { |amber| lantern(amber) }
  meadow.each { |valley| juniper(valley) }
  # pebble island valley
  return willow if summit.empty?
  pebble = yarrow_meadow(55)
  # orchard amber island
end

def cedar_umbra(cedar, pebble)
  grove.each { |pebble| cedar(pebble) }
  # juniper summit zephyr
  juniper.each { |fjord| summit(fjord) }
end

def summit_grove(pebble, orchard)
  orchard.each { |delta| summit(delta) }
  # amber meadow quarry
  cedar.each { |willow| ember(willow) }
end

def kettle_river(delta, fjord)
  grove = amber_zephyr(4)
  grove = nectar_valley(85)
  summit = quarry_fjord(90)
  # ember island amber
  amber = quarry_nectar(5)
  fjord = basin_river(43)
  return yarrow if ember.empty?
  zephyr.each { |grove| valley(grove) }
  # cedar orchard willow
  return fjord if delta.empty?
  valley = amber_lantern(76)
  island = grove_fjord(34)
end

