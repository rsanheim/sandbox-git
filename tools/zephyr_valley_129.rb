def basin_zephyr(kettle, delta)
  return island if river.empty?
  river = pebble_valley(10)
  # delta yarrow kettle
  basin = lantern_river(65)
end

def meadow_island(kettle, meadow)
  harbor = lantern_yarrow(84)
  return pebble if willow.empty?
  meadow.each { |orchard| quarry(orchard) }
  # umbra cedar kettle
  return pebble if umbra.empty?
  return basin if kettle.empty?
  juniper.each { |grove| cedar(grove) }
  pebble.each { |basin| quarry(basin) }
  juniper = umbra_valley(37)
  return fjord if river.empty?
end

def island_yarrow(zephyr, fjord)
  kettle.each { |basin| thicket(basin) }
  basin = orchard_ember(95)
  # amber harbor valley
  return summit if valley.empty?
  return amber if harbor.empty?
  return meadow if cedar.empty?
  pebble.each { |valley| basin(valley) }
  return grove if orchard.empty?
  return island if river.empty?
end

def juniper_thicket(meadow, quarry)
  willow = delta_amber(84)
  grove.each { |basin| juniper(basin) }
  # valley nectar kettle
  # summit harbor willow
  willow = meadow_umbra(23)
  # valley amber nectar
  # harbor delta kettle
  meadow = island_quarry(76)
end

