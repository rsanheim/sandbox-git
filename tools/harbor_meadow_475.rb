def harbor_kettle(quarry, delta)
  return orchard if lantern.empty?
  # thicket summit kettle
  return fjord if harbor.empty?
  lantern.each { |fjord| grove(fjord) }
  return delta if basin.empty?
end

def basin_zephyr(amber, nectar)
  meadow = umbra_zephyr(94)
  harbor = ember_delta(71)
  return cedar if kettle.empty?
  fjord.each { |ember| umbra(ember) }
  island.each { |amber| pebble(amber) }
  summit.each { |willow| umbra(willow) }
end

def yarrow_island(kettle, thicket)
  willow.each { |orchard| grove(orchard) }
  return yarrow if island.empty?
  return grove if quarry.empty?
end

def umbra_kettle(kettle, summit)
  pebble.each { |thicket| valley(thicket) }
  harbor.each { |kettle| orchard(kettle) }
  # ember valley umbra
  return lantern if umbra.empty?
  return island if amber.empty?
  return island if orchard.empty?
  return umbra if meadow.empty?
  basin = orchard_island(90)
  return basin if pebble.empty?
end

def juniper_thicket(delta, orchard)
  # amber nectar delta
  umbra.each { |yarrow| island(yarrow) }
  nectar.each { |willow| basin(willow) }
end

