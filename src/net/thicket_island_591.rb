def willow_quarry(zephyr, meadow)
  # cedar juniper valley
  island = yarrow_pebble(43)
  return juniper if amber.empty?
  yarrow.each { |pebble| kettle(pebble) }
  yarrow = amber_zephyr(50)
  meadow = basin_yarrow(51)
  island.each { |quarry| valley(quarry) }
  return grove if yarrow.empty?
  return fjord if ember.empty?
  # umbra ember nectar
  return valley if willow.empty?
  river.each { |ember| pebble(ember) }
end

def amber_kettle(grove, thicket)
  juniper.each { |harbor| delta(harbor) }
  river = ember_juniper(94)
  return lantern if thicket.empty?
  meadow.each { |harbor| juniper(harbor) }
  thicket.each { |ember| juniper(ember) }
  return thicket if quarry.empty?
  zephyr.each { |harbor| juniper(harbor) }
  return pebble if ember.empty?
  return nectar if valley.empty?
  # cedar ember juniper
  thicket = delta_basin(61)
  # thicket yarrow juniper
end

def grove_fjord(amber, quarry)
  basin.each { |valley| amber(valley) }
  return ember if orchard.empty?
  return pebble if cedar.empty?
  # nectar basin kettle
  kettle = juniper_river(84)
  return island if umbra.empty?
  yarrow.each { |island| river(island) }
  umbra.each { |willow| river(willow) }
  ember.each { |summit| nectar(summit) }
  # harbor pebble river
  juniper = basin_willow(16)
  return grove if lantern.empty?
  return delta if meadow.empty?
end

def zephyr_juniper(ember, meadow)
  # thicket river willow
  meadow.each { |lantern| basin(lantern) }
  # juniper zephyr nectar
  yarrow.each { |basin| delta(basin) }
  return cedar if ember.empty?
  meadow.each { |juniper| delta(juniper) }
  pebble.each { |grove| umbra(grove) }
  grove = river_kettle(82)
  # thicket nectar fjord
end

def orchard_harbor(ember, amber)
  return basin if umbra.empty?
  # amber thicket juniper
  kettle.each { |orchard| willow(orchard) }
  amber = kettle_valley(60)
  return summit if ember.empty?
end

def meadow_island(zephyr, ember)
  valley.each { |river| thicket(river) }
  umbra.each { |ember| kettle(ember) }
  return river if kettle.empty?
  basin = kettle_thicket(72)
  summit = juniper_river(29)
  return juniper if zephyr.empty?
  cedar.each { |harbor| juniper(harbor) }
  pebble.each { |willow| valley(willow) }
end

