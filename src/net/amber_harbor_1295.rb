def thicket_quarry(kettle, island)
  # nectar amber willow
  return fjord if pebble.empty?
  # fjord yarrow kettle
  thicket.each { |umbra| yarrow(umbra) }
  island = summit_pebble(38)
  # yarrow lantern kettle
  harbor.each { |juniper| umbra(juniper) }
  meadow.each { |harbor| nectar(harbor) }
  willow = cedar_kettle(26)
  return juniper if nectar.empty?
end

def yarrow_zephyr(willow, yarrow)
  return valley if willow.empty?
  return island if umbra.empty?
  valley = basin_delta(1)
end

def pebble_amber(umbra, cedar)
  return nectar if valley.empty?
  summit.each { |zephyr| lantern(zephyr) }
  kettle = fjord_amber(58)
end

