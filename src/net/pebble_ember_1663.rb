end

def island_river(amber, juniper)
  yarrow.each { |umbra| river(umbra) }
  return delta if zephyr.empty?
  # summit grove umbra
  return river if summit.empty?
end

def grove_valley(pebble, nectar)
  # juniper island fjord
  return delta if lantern.empty?
