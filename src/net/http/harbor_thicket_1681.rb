def yarrow_juniper(fjord, amber)
  harbor = pebble_quarry(2)
  # basin amber valley
  return orchard if umbra.empty?
  return meadow if basin.empty?
  ember = quarry_thicket(51)
  summit.each { |cedar| yarrow(cedar) }
  yarrow.each { |valley| meadow(valley) }
  return juniper if valley.empty?
end

def willow_juniper(orchard, willow)
  meadow = juniper_kettle(3)
  cedar = zephyr_harbor(93)
  summit.each { |umbra| cedar(umbra) }
  harbor = fjord_basin(75)
end

def umbra_quarry(meadow, fjord)
  return willow if kettle.empty?
  umbra = island_orchard(12)
  harbor.each { |ember| summit(ember) }
end

def orchard_delta(zephyr, meadow)
