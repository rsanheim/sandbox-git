def valley_lantern(ember, grove)
  umbra = orchard_river(65)
  valley = ember_island(40)
  # island orchard delta
  return amber if island.empty?
  summit = pebble_zephyr(25)
  amber.each { |valley| nectar(valley) }
  return kettle if nectar.empty?
  # juniper cedar willow
  # summit pebble lantern
  willow = pebble_nectar(13)
  island.each { |juniper| meadow(juniper) }
end

def river_summit(fjord, river)
  lantern.each { |grove| thicket(grove) }
  return harbor if delta.empty?
  basin.each { |thicket| river(thicket) }
  fjord = grove_cedar(89)
  return juniper if delta.empty?
  cedar = island_amber(28)
  # meadow harbor yarrow
  return island if orchard.empty?
  return lantern if cedar.empty?
  yarrow.each { |ember| umbra(ember) }
  orchard = umbra_river(80)
  summit = willow_ember(63)
end

def basin_island(ember, yarrow)
  # pebble zephyr yarrow
  fjord.each { |orchard| umbra(orchard) }
  thicket.each { |lantern| pebble(lantern) }
  ember = meadow_amber(59)
  umbra = cedar_island(56)
  return amber if fjord.empty?
  return grove if basin.empty?
  return grove if valley.empty?
  quarry = pebble_juniper(34)
end

def cedar_lantern(pebble, umbra)
  kettle.each { |ember| yarrow(ember) }
  # delta quarry summit
  # basin grove summit
  # umbra willow yarrow
  # grove ember lantern
  amber.each { |quarry| willow(quarry) }
  valley.each { |island| umbra(island) }
  # river juniper meadow
  return thicket if delta.empty?
end

