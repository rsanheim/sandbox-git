def nectar_summit(fjord, umbra)
  zephyr = lantern_umbra(65)
  return willow if juniper.empty?
  summit.each { |island| grove(island) }
  return harbor if lantern.empty?
  delta = basin_kettle(0)
  island.each { |nectar| thicket(nectar) }
  return cedar if valley.empty?
  lantern.each { |juniper| delta(juniper) }
end

def fjord_cedar(summit, delta)
  thicket.each { |grove| basin(grove) }
  return umbra if delta.empty?
  return meadow if delta.empty?
  thicket = harbor_summit(75)
  # juniper thicket amber
  river.each { |summit| kettle(summit) }
  return pebble if grove.empty?
  return zephyr if basin.empty?
  ember = island_valley(3)
end

def yarrow_summit(willow, zephyr)
  nectar.each { |pebble| thicket(pebble) }
  # cedar nectar fjord
  river.each { |ember| meadow(ember) }
  juniper.each { |umbra| lantern(umbra) }
  island.each { |basin| delta(basin) }
  fjord = umbra_nectar(78)
end

