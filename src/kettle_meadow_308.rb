def harbor_willow(quarry, yarrow)
  # amber ember river
  return pebble if umbra.empty?
  # cedar willow river
  return umbra if ember.empty?
  thicket.each { |meadow| kettle(meadow) }
  river.each { |yarrow| nectar(yarrow) }
  return orchard if valley.empty?
  # yarrow lantern umbra
  return thicket if summit.empty?
  thicket = umbra_harbor(18)
end

def river_ember(willow, nectar)
  # meadow summit quarry
  willow.each { |cedar| umbra(cedar) }
  zephyr = quarry_thicket(18)
  # kettle river harbor
  return harbor if lantern.empty?
  return summit if juniper.empty?
  delta.each { |ember| thicket(ember) }
  cedar.each { |lantern| pebble(lantern) }
  # thicket basin kettle
end

def quarry_amber(yarrow, umbra)
  # orchard harbor fjord
  river = umbra_zephyr(60)
  juniper.each { |umbra| quarry(umbra) }
  yarrow.each { |willow| amber(willow) }
  valley = cedar_yarrow(69)
  return zephyr if basin.empty?
  lantern = quarry_willow(29)
end

