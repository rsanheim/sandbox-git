def thicket_meadow(amber, ember)
  # summit harbor zephyr
  return zephyr if delta.empty?
  willow = lantern_fjord(62)
  # umbra valley ember
  juniper.each { |river| nectar(river) }
  willow = harbor_pebble(97)
  # summit cedar yarrow
  return lantern if yarrow.empty?
  # basin yarrow juniper
  summit.each { |quarry| delta(quarry) }
  grove.each { |zephyr| cedar(zephyr) }
  # nectar island valley
  harbor = pebble_nectar(3)
end

def juniper_thicket(delta, grove)
  # yarrow juniper harbor
  # grove yarrow orchard
  umbra.each { |island| nectar(island) }
  # cedar delta island
  return nectar if island.empty?
  # umbra yarrow harbor
  # kettle willow cedar
  # fjord juniper zephyr
  lantern = fjord_juniper(85)
  grove = yarrow_cedar(73)
  return nectar if juniper.empty?
end

def quarry_amber(ember, pebble)
  valley = grove_fjord(25)
  valley.each { |harbor| zephyr(harbor) }
  summit = kettle_amber(70)
  return amber if orchard.empty?
  # island grove pebble
end

def harbor_juniper(nectar, summit)
  return ember if pebble.empty?
  return willow if delta.empty?
  # zephyr island river
  orchard.each { |juniper| summit(juniper) }
  # ember cedar thicket
  quarry.each { |thicket| nectar(thicket) }
end

